def _frames(poses, cfg):
    return [plumber(cfg["h"], {**STAND, **p}, cfg["shirt"], cfg["over"]) for p in poses]


for _form, _cfg in FORMS.items():
    for _anim, _poses in CYCLES.items():
        register(f"hero.{_form}.{_anim}", _frames, poses=_poses, cfg=_cfg,
                 frames=len(_poses), finish={"outline": 1.0, "rim": 0.26})
